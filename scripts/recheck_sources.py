#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Re-check every official source URL and mark rows whose source changed.

Runs daily via GitHub Actions (.github/workflows/maintenance.yml).
Method: fetch each URL, store a SHA-256 of the normalized body in
data/integrated/monitoring/history.json, and flag CHANGED when the hash
differs from the previous run. A fetch error marks the row with the error —
never silently dropped. Regenerates data/integrated/monitoring.json and
monitoring.html inputs (site rebuild picks it up).
"""
import hashlib, json, os, re, sys, urllib.request, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data", "integrated")
HIST = os.path.join(D, "monitoring")
os.makedirs(HIST, exist_ok=True)
TODAY = datetime.date.today().isoformat()
UA = {"User-Agent": "Mozilla/5.0 (compatible; Poker4-source-monitor/1.0)"}

def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=45) as r:
        body = r.read()
    return body

def norm_hash(body):
    text = re.sub(rb"\s+", b" ", body).strip().lower()
    return hashlib.sha256(text).hexdigest()

def main():
    with open(os.path.join(D, "sources.json")) as f:
        sources = json.load(f)["sources"]
    hist_path = os.path.join(HIST, "history.json")
    history = {}
    if os.path.exists(hist_path):
        with open(hist_path) as f:
            history = json.load(f)
    checks, changed, errors = [], [], []
    for s in sources:
        row = dict(label=s["label"], url=s["url"], last_checked=TODAY)
        try:
            h = norm_hash(fetch(s["url"]))
            prev = history.get(s["url"], {})
            if prev.get("hash") and prev["hash"] != h:
                row["status"] = "CHANGED since %s" % prev.get("date", "?")
                row["changed"] = "YES — review required"
                changed.append(s["label"])
            else:
                row["status"] = "unchanged (baseline)" if not prev.get("hash") else "unchanged"
                row["changed"] = "no"
            history[s["url"]] = dict(hash=h, date=TODAY)
        except Exception as ex:
            row["status"] = "FETCH ERROR: %s" % ex
            row["changed"] = "unknown — fetch failed"
            errors.append("%s (%s)" % (s["label"], ex))
        checks.append(row)
    with open(hist_path, "w") as f:
        json.dump(history, f, indent=1)
    with open(os.path.join(D, "monitoring.json"), "w") as f:
        json.dump(dict(meta=dict(built=TODAY, note="Generated by scripts/recheck_sources.py"),
                       checks=checks), f, indent=1)
    print("recheck_sources: %d urls, %d changed, %d errors" % (len(checks), len(changed), len(errors)))
    for c in changed: print("  CHANGED:", c)
    for e in errors: print("  ERROR:", e)
    # exit 0 even with changes — changes are reported, not failures

if __name__ == "__main__":
    main()
