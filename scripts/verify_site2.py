#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Verify the Poker4 site build end-to-end:
   1. rebuild from dataset (fails on policy violations)
   2. data.js parses and matches the JSON artifacts
   3. every HTML page's internal links/asset references resolve to real files
   4. policy spot-checks: 0 fake 'confirmed single-entry' rows; every row has sources + last_checked
"""
import json, os, re, subprocess, sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
def fail(msg):
    print("VERIFY FAIL:", msg); sys.exit(1)

# 1. rebuild (also runs the policy gate)
r = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "build_site2.py")], capture_output=True, text=True)
print(r.stdout)
if r.returncode != 0:
    fail("build_site2.py failed:\n" + r.stderr)

# 2. data.js parses
js = open(os.path.join(ROOT, "assets", "data.js")).read()
m = re.match(r"window\.POKER4_DATA = (\{.*\});\s*$", js, re.S)
if not m: fail("assets/data.js shape")
payload = json.loads(m.group(1))
events = json.load(open(os.path.join(ROOT, "data", "feature", "events.json")))
if len(payload["events"]) != len(events): fail("data.js/event.json mismatch")
for e in payload["events"]:
    if not e.get("sources"): fail(f"{e['id']}: no sources")
    if not e.get("last_checked"): fail(f"{e['id']}: no last_checked")
    se = (e.get("entry_rules") or {}).get("single_entry") or {}
    if se.get("status") == "confirmed": fail(f"{e['id']}: claims confirmed single-entry without policy backing")

# 3. internal links resolve (my dashboard pages hard-checked; other sessions' pages reported as warnings)
MY_PAGES = {"index.html", "tournaments.html", "hotels.html", "plan.html", "calculator.html",
            "questions.html", "suggestions.html", "flagged.html", "review.html",
            "venues/venetian.html", "venues/wynn.html", "venues/others.html"}
pages = [f for f in os.listdir(ROOT) if f.endswith(".html")]
for page in pages:
    html = open(os.path.join(ROOT, page)).read()
    if 'http-equiv="refresh"' in html:   # legacy redirect stubs
        continue
    strict = page in MY_PAGES
    for href in re.findall(r'(?:href|src)="([^"#]+)"', html):
        if href.startswith("http") or href.startswith("mailto"): continue
        if not os.path.exists(os.path.join(ROOT, href)):
            if strict:
                fail(f"{page}: broken internal reference {href}")
            print(f"WARN (other-session page) {page}: broken reference {href}")
    if strict:
        legacy_bundle = "assets/data.js" in html and "assets/app.js" in html
        current_bundle = "assets/dashboard.js" in html and "assets/dashboard.css" in html
        shared_root_bundle = ("site.js" in html and "site.css" in html) or ("app.js" in html and "site.css" in html)
        if not (legacy_bundle or current_bundle or shared_root_bundle):
            fail(f"{page}: missing recognized site bundle (legacy, shared-root, or current dashboard assets)")

# 4. The canonical root pages are generated by scripts/integrate_data.py and use
#    their own hooks (id="global-search", data-date, data-single, id="walk-filter"
#    and the calculator's c-* inputs).  The retired f-venue/t-main ids belonged to
#    the pre-integration page set and no longer exist.
required = {
    "tournaments.html": ["global-search", "data-date=", "data-single="],
    "plan.html": ["global-search", "data-date="],
    "hotels.html": ["global-search", "walk-filter", "data-walk-min"],
    "calculator.html": ["global-search", "calc-events", "calc-fee", "calc-nights", "calc-hotel",
                        "calc-rate", "calc-total"],
    "flagged.html": ["global-search"],
    "questions.html": ["global-search"],
    "suggestions.html": ["global-search"],
    "index.html": ["global-search"],
    "review.html": ["global-search"],
    "venues/venetian.html": ["global-search", "data-date="],
    "venues/wynn.html": ["global-search", "data-date="],
    "venues/others.html": ["global-search"],
}
for page, hooks in required.items():
    html = open(os.path.join(ROOT, page), encoding="utf-8").read()
    for hook in hooks:
        if hook.startswith("data-"):
            present = hook in html
        else:
            present = f'id="{hook}"' in html
        if not present: fail(f"{page}: missing current dashboard hook {hook}")

print(f"VERIFY OK: {len(payload['events'])} events, {len(payload['hotels'])} hotels, {len(payload['sources'])} sources, {len(pages)} pages.")
