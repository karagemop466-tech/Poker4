# schedule-row -> sheet mapping is derived from the structure URL printed on the
# official schedule page (file name dse_nov_2026-structure_N.pdf).
def sheet_from_pdf(name: str) -> str:
    import re
    m = re.search(r"structure_(\d+)\.pdf", name or "")
    return m.group(1) if m else ""
