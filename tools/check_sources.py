#!/usr/bin/env python3
"""Re-check every official source URL and flag changes.

Reads the monitored-source list from planner/assets/data.js, fetches each URL,
compares the response to the last stored snapshot (planner/data/snapshots.json),
and:
  * updates each source's last-checked date in data.js,
  * appends a dated entry to the change log when a value changed,
  * writes the new snapshot hashes back to snapshots.json.

Run manually:  python3 tools/check_sources.py
Scheduled:      .github/workflows/monitor.yml (cron)
Exit code 0 on success (even if some sources are unreachable — unreachable is
logged as a change, not a crash). Network access is required at run time.
"""
import hashlib
import json
import os
import sys
import urllib.request
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_JS = os.path.join(ROOT, "planner", "assets", "data.js")
SNAP_DIR = os.path.join(ROOT, "planner", "data")
SNAP_FILE = os.path.join(SNAP_DIR, "snapshots.json")
UA = "Poker4-Monitor/1.0 (+official-source re-check)"


def load_data_js(path):
    """Return the parsed PLANNER_DATA object from the generated data.js."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    start = text.index("{")
    end = text.rindex("};") + 1
    return json.loads(text[start:end])


def save_data_js(path, data):
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/gen_planner_data.py — verified Venetian DSE IV dataset.\n")
        f.write("// Updated by tools/check_sources.py — last-checked dates and change log.\n")
        f.write("window.PLANNER_DATA = ")
        f.write(json.dumps(data, indent=2))
        f.write(";\n")


def fetch(url):
    """Return (status, body_hash, length). status 'error' on failure."""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=25) as r:
            body = r.read()
        return r.status, hashlib.sha256(body).hexdigest(), len(body)
    except Exception as e:  # noqa: BLE001 — we want to log any failure
        return "error", hashlib.sha256(repr(e).encode()).hexdigest(), 0


def main():
    data = load_data_js(DATA_JS)
    os.makedirs(SNAP_DIR, exist_ok=True)
    if os.path.exists(SNAP_FILE):
        with open(SNAP_FILE, encoding="utf-8") as f:
            snapshots = json.load(f)
    else:
        snapshots = {}

    today = date.today().isoformat()
    changed = 0
    for src in data["monitoring_sources"]:
        url = src["url"]
        status, digest, length = fetch(url)
        prev = snapshots.get(url, {})
        prev_digest = prev.get("digest")
        src["last_checked"] = today
        if prev_digest is None:
            note = f"first check: HTTP {status}, {length} bytes"
        elif prev_digest != digest:
            note = f"CHANGED: HTTP {status}, {length} bytes (was {prev.get('length')} bytes)"
            changed += 1
        else:
            note = f"no change: HTTP {status}, {length} bytes"
        if status == "error":
            note = f"UNREACHABLE: {url}"
            src["status"] = "unreachable"
            changed += 1
        src["status"] = src.get("status") if status == "error" else "ok"
        snapshots[url] = {"digest": digest, "length": length, "status": status, "checked": today}
        print(f"[{note}] {src['label']}")
        data["change_log"].append({"date": today, "source": src["label"], "url": url, "change": note})

    # keep only the most recent entry per source to avoid unbounded growth
    seen = set()
    trimmed = []
    for c in reversed(data["change_log"]):
        key = c["source"]
        if key in seen:
            continue
        seen.add(key)
        trimmed.append(c)
    data["change_log"] = list(reversed(trimmed))

    with open(SNAP_FILE, "w", encoding="utf-8") as f:
        json.dump(snapshots, f, indent=2, sort_keys=True)
    save_data_js(DATA_JS, data)
    print(f"\nDone. {changed} source(s) changed or unreachable. State written to {SNAP_FILE}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
